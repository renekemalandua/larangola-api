export async function seedWorkspaces(prisma: PrismaClient, agentData: any, categoryId: string) {
  console.log('💼 Seeding 20 Workspaces for presentation...');

  for (const item of MOCK_WORKSPACES) {
    // Check if property with this title already exists
    const existing = await prisma.property.findFirst({
      where: { title: item.title }
    });

    if (existing) {
      continue;
    }

    const price = item.pricePerHour || item.pricePerDay || 50000;

    await prisma.property.create({
      data: {
        agentId: agentData.agent.id,
        categoryId: categoryId,
        title: item.title,
        description: item.description,
        address: item.address,
        city: item.city,
        state: 'Luanda',
        country: 'Angola',
        propertyType: 'office',
        price: price,
        listingType: ListingType.rent,
        status: PropertyStatus.published,
        statusUpdatedAt: new Date(),
        images: item.photos,
        isHighlighted: Math.random() > 0.6,
        workspaceDetails: {
          create: {
            workspaceType: item.workspaceType,
            pricingType: item.pricingType,
            pricePerHour: item.pricePerHour,
            pricePerDay: item.pricePerDay,
            capacitySeats: item.capacitySeats,
            minBookingHours: item.minBookingHours,
            hasHighSpeedWifi: item.hasHighSpeedWifi,
            hasGenerator: item.hasGenerator,
            hasProjector: item.hasProjector,
            hasWhiteboard: item.hasWhiteboard,
            hasAirConditioning: item.hasAirConditioning,
            hasCoffeeBreak: item.hasCoffeeBreak,
            hasParking: item.hasParking,
          }
        }
      }
    });
  }

  console.log('✅ 20 Workspaces seeded successfully for testing agent!');
}
